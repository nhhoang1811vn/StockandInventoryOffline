## 单据

单据记录商品进出门店的库存变动。

### 入库
- 商品**到达**门店时，创建入库单。
- 单据中的数量会**加到**库存。

### 出库
- 商品**离开**门店时（例如销售），创建出库单。
- 单据中的数量会从库存中**减去**。

### 添加商品
- 从目录中选择商品，或
- 用相机**扫描条码**。

### 连续扫描
- 连续扫描条码。每次扫描都会**添加该商品，并把数量加 1**。
- 也可以在每次扫描后**手动**输入数量。
- 在**设置**中选择模式。

### 自动创建商品
- 在入库单中添加的**新商品**（资料完整）会**保存到目录**。
- 不能在出库单中添加新商品。该商品必须已经在库存中。

### 删除
- **长按**单据或明细行即可删除。

> 删除单据会改变库存。只能删除**最新**的单据。删除更早的单据可能导致数量不正确。

### 筛选和排序
- 使用工具栏**筛选**或**排序**单据。
