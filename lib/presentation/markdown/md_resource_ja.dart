## 伝票

伝票は、店舗への入庫と出庫を記録します。

### 入庫
- 商品が店舗に**届いた**ときに入庫伝票を作ります。
- 伝票の数量は在庫に**加算**されます。

### 出庫
- 商品が店舗から**出る**とき（販売など）に出庫伝票を作ります。
- 伝票の数量は在庫から**減算**されます。

### 商品を追加
- カタログから商品を選ぶか、
- カメラで**バーコードを読み取り**ます。

### 連続読み取り
- バーコードを続けて読み取ります。1 回の読み取りで**商品を追加し、数量を 1 増やします**。
- または、読み取りのたびに数量を**手入力**します。
- モードは**設定**で選びます。

### 商品の自動作成
- 入庫伝票に追加した**新しい商品**（情報がそろっている場合）は**カタログに保存**されます。
- 出庫伝票に新しい商品は追加できません。在庫にすでにある商品だけです。

### 削除
- 伝票または明細を**長押し**して削除します。

> 伝票を削除すると在庫が変わります。削除できるのは**最新**の伝票だけです。それより古い伝票を削除すると、数量が正しくなくなることがあります。

### 絞り込みと並べ替え
- ツールバーで伝票を**絞り込み**または**並べ替え**ます。
